export function getProvinces(): string[] {
  return IRAN_PROVINCES.map((p) => p.name);
}

export function getCitiesByProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const found = IRAN_PROVINCES.find((p) => p.name === provinceName.trim());
  return found ? [...found.cities] : [];
}

export function findProvinceByCity(cityName: string): string | null {
  if (!cityName) return null;
  const cleanCity = cityName.trim();
  for (const prov of IRAN_PROVINCES) {
    if (prov.cities.includes(cleanCity)) {
      return prov.name;
    }
  }
  return null;
}

export function isValidProvince(provinceName: string): boolean {
  if (!provinceName) return false;
  return IRAN_PROVINCES.some((p) => p.name === provinceName.trim());
}

export function isValidCity(provinceName: string, cityName: string): boolean {
  if (!provinceName || !cityName) return false;
  const cities = getCitiesByProvince(provinceName);
  return cities.includes(cityName.trim());
}
